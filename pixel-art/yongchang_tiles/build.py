def atlas(rows: int = ROWS) -> Sprite:
    return Sprite(COLS * TILE, rows * TILE, palette=PAL)


def origin(index: int) -> tuple[int, int]:
    return (index % COLS) * TILE, (index // COLS) * TILE


def fill(s: Sprite, index: int, color: int) -> tuple[int, int]:
    x, y = origin(index)
    s.rect(x, y, x + TILE - 1, y + TILE - 1, color)
    return x, y


def px(s: Sprite, x: int, y: int, color: int) -> None:
    s.px(x, y, color)


def rect(s: Sprite, ox: int, oy: int, x0: int, y0: int, x1: int, y1: int, color: int) -> None:
    s.rect(ox + x0, oy + y0, ox + x1, oy + y1, color)


def line(s: Sprite, ox: int, oy: int, x0: int, y0: int, x1: int, y1: int, color: int) -> None:
    s.line(ox + x0, oy + y0, ox + x1, oy + y1, color)


def dash_row(s: Sprite, ox: int, oy: int, y: int, color: int,
             width: int = 4, period: int = 8, offset: int = 0) -> None:
    for x in range(offset, TILE, period):
        for xx in range(x, min(TILE, x + width)):
            px(s, ox + xx, oy + y, color)


def mud_tile(s: Sprite, index: int, variant: int = 0, base: int = EARTH) -> None:
    ox, oy = fill(s, index, base)
    rng = random.Random(3100 + variant)
    for _ in range(30):
        x = rng.randrange(2, TILE - 3)
        y = rng.randrange(2, TILE - 3)
        color = EARTH_DARK if rng.random() < 0.58 else EARTH_LIGHT
        length = rng.randrange(2, 5)
        rect(s, ox, oy, x, y, x + length - 1, y, color)
        if rng.random() < 0.14:
            px(s, ox + x, oy + y + 1, EARTH_DARKEST)
    for _ in range(3):
        x = rng.randrange(3, TILE - 9)
        y = rng.randrange(4, TILE - 5)
        w = rng.randrange(3, 7)
        rect(s, ox, oy, x, y, x + w, y + 1, WATER_LIGHT)
        rect(s, ox, oy, x + 1, y - 1, x + w - 1, y - 1, EARTH_DARK)
        px(s, ox + x + w // 2, oy + y, WATER_CREST)
    for _ in range(9):
        x = rng.randrange(2, TILE - 2)
        y = rng.randrange(2, TILE - 2)
        px(s, ox + x, oy + y, EARTH_DARKEST if rng.random() < 0.6 else SAND)


def sand_tile(s: Sprite, index: int, variant: int = 0) -> None:
    ox, oy = fill(s, index, SAND)
    rng = random.Random(4200 + variant)
    for _ in range(32):
        x = rng.randrange(1, TILE - 1)
        y = rng.randrange(1, TILE - 1)
        px(s, ox + x, oy + y, EARTH_LIGHT if rng.random() < 0.7 else EARTH_DARK)
    for y in (9, 22):
        for x in range((variant * 3 + y) % 5, TILE, 11):
            rect(s, ox, oy, x, y, min(TILE - 1, x + 3), y, EARTH_LIGHT)
            px(s, ox + x, oy + y + 1, EARTH)
    for _ in range(4):
        x = rng.randrange(4, TILE - 6)
        y = rng.randrange(4, TILE - 4)
        px(s, ox + x, oy + y, WATER_LIGHT)


def water_tile(s: Sprite, index: int, deep: bool = False, variant: int = 0) -> None:
    base = WATER_DEEP if deep else WATER
    wave = WATER_LIGHT if deep else WATER_CREST
    ox, oy = fill(s, index, base)
    for row, y in enumerate((4, 12, 20, 28)):
        offset = (variant * 3 + row * 2) % 8
        dash_row(s, ox, oy, y, wave, width=5 if not deep else 3, period=11, offset=offset)
        dash_row(s, ox, oy, y + 1, WATER_LIGHT if not deep else WATER, width=2, period=11,
                 offset=(offset + 3) % 8)
    rng = random.Random(5200 + variant + (10 if deep else 0))
    for _ in range(6 if deep else 10):
        x = rng.randrange(1, TILE - 2)
        y = rng.randrange(1, TILE - 2)
        px(s, ox + x, oy + y, wave)


def reed_bed(s: Sprite, index: int) -> None:
    mud_tile(s, index, variant=3, base=EARTH_DARK)
    ox, oy = origin(index)
    rng = random.Random(6150)
    for _ in range(17):
        x = rng.randrange(2, TILE - 2)
        y = rng.randrange(9, TILE - 2)
        height = rng.randrange(5, 13)
        color = REED if rng.random() < 0.72 else REED_DARK
        line(s, ox, oy, x, y, x + rng.randrange(-1, 2), y - height, color)
        if rng.random() < 0.58:
            px(s, ox + x + rng.choice((-1, 1)), oy + y - height + 1, REED_LIGHT)
    for y in (17, 25):
        dash_row(s, ox, oy, y, REED_DARK, width=4, period=9, offset=2)


def stone_road(s: Sprite, index: int, variant: int = 0) -> None:
    ox, oy = fill(s, index, STONE_DARK)
    for row in range(2):
        y0 = row * 16 + 1
        y1 = y0 + 13
        joints = (0, 16) if row == 0 else (8, 24)
        spans = ((1, 15), (17, 30)) if row == 0 else ((1, 7), (9, 23), (25, 30))
        for x0, x1 in spans:
            rect(s, ox, oy, x0, y0, x1, y1, STONE)
            # 上缘受光、下缘落影，让每块石板有清晰的凸起感。
            rect(s, ox, oy, x0, y0, x1, y0, STONE_HIGHLIGHT)
            rect(s, ox, oy, x0, y0 + 1, min(x1, x0 + 7), y0 + 1, STONE_LIGHT)
            rect(s, ox, oy, x0, y1 - 1, x1, y1, STONE_SHADOW)
            rect(s, ox, oy, x0, y1, x1, y1, INK)
    rng = random.Random(7100 + variant)
    for _ in range(14):
        x = rng.randrange(3, TILE - 3)
        y = rng.randrange(3, TILE - 3)
        px(s, ox + x, oy + y, STONE_HIGHLIGHT if rng.random() < 0.35 else STONE_SHADOW)
    if variant:
        rect(s, ox, oy, 9, 20, 14, 21, STONE_SHADOW)
        px(s, ox + 13, oy + 9, STONE_HIGHLIGHT)


def earth_road(s: Sprite, index: int, variant: int = 0) -> None:
    ox, oy = fill(s, index, EARTH)
    for y0, y1 in ((7, 9), (22, 24)):
        rect(s, ox, oy, 0, y0, TILE - 1, y1, EARTH_LIGHT)
        dash_row(s, ox, oy, y0, EARTH_DARK, width=7, period=13, offset=variant * 3)
        dash_row(s, ox, oy, y1, EARTH, width=4, period=13, offset=(variant * 3 + 5) % 9)
    rng = random.Random(8100 + variant)
    for _ in range(22):
        x = rng.randrange(1, TILE - 1)
        y = rng.randrange(1, TILE - 1)
        px(s, ox + x, oy + y, EARTH_DARK if rng.random() < 0.62 else EARTH_LIGHT)
    for _ in range(5):
        x = rng.randrange(2, TILE - 5)
        y = rng.randrange(2, TILE - 3)
        rect(s, ox, oy, x, y, x + 2, y + 1, STONE_SHADOW)
        px(s, ox + x, oy + y, STONE)


def dock_planks(s: Sprite, index: int, vertical: bool = True) -> None:
    ox, oy = fill(s, index, WOOD_DARK)
    # 高光与木钉都内缩，保证相邻甲板的拼接边颜色一致，没有一格一框的断口。
    if vertical:
        for x0 in range(0, TILE, 8):
            rect(s, ox, oy, x0 + 1, 0, x0 + 6, TILE - 1, WOOD)
            rect(s, ox, oy, x0 + 2, 5, x0 + 3, 11, WOOD_LIGHT)
            rect(s, ox, oy, x0 + 2, 20, x0 + 3, 26, WOOD_LIGHT)
            rect(s, ox, oy, x0 + 7, 0, x0 + 7, TILE - 1, WOOD_DARK)
            for y in (7, 23):
                px(s, ox + x0 + 4, oy + y, STONE_HIGHLIGHT)
                px(s, ox + x0 + 5, oy + y + 1, WOOD_DARK)
    else:
        for y0 in range(0, TILE, 8):
            rect(s, ox, oy, 0, y0 + 1, TILE - 1, y0 + 6, WOOD)
            rect(s, ox, oy, 4, y0 + 2, 12, y0 + 3, WOOD_LIGHT)
            rect(s, ox, oy, 20, y0 + 2, 27, y0 + 3, WOOD_LIGHT)
            rect(s, ox, oy, 0, y0 + 7, TILE - 1, y0 + 7, WOOD_DARK)
            for x in (8, 24):
                px(s, ox + x, oy + y0 + 4, STONE_HIGHLIGHT)
                px(s, ox + x + 1, oy + y0 + 5, WOOD_DARK)


def shore_side(s: Sprite, index: int, side: str) -> None:
    ox, oy = fill(s, index, WATER)
    rng = random.Random(9100 + index)
    for pos in range(TILE):
        edge = 11 + ((pos // 4 + index) % 3)
        if side == "n":
            rect(s, ox, oy, pos, edge, pos, TILE - 1, EARTH)
            px(s, ox + pos, oy + edge, SAND)
            px(s, ox + pos, oy + edge + 1, EARTH_DARK)
            rect(s, ox, oy, pos, edge - 3, pos, edge - 1, WATER_DEEP)
            if pos % 4 in (0, 1):
                px(s, ox + pos, oy + edge - 1, WATER_CREST)
        elif side == "s":
            boundary = TILE - 1 - edge
            rect(s, ox, oy, pos, 0, pos, boundary, EARTH)
            px(s, ox + pos, oy + boundary, SAND)
            px(s, ox + pos, oy + boundary - 1, EARTH_DARK)
            rect(s, ox, oy, pos, boundary + 1, pos, boundary + 3, WATER_DEEP)
            if pos % 4 in (0, 1):
                px(s, ox + pos, oy + boundary + 1, WATER_CREST)
        elif side == "e":
            boundary = TILE - 1 - edge
            rect(s, ox, oy, 0, pos, boundary, pos, EARTH)
            px(s, ox + boundary, oy + pos, SAND)
            px(s, ox + boundary - 1, oy + pos, EARTH_DARK)
            rect(s, ox, oy, boundary + 1, pos, boundary + 3, pos, WATER_DEEP)
            if pos % 4 in (0, 1):
                px(s, ox + boundary + 1, oy + pos, WATER_CREST)
        else:
            rect(s, ox, oy, edge, pos, TILE - 1, pos, EARTH)
            px(s, ox + edge, oy + pos, SAND)
            px(s, ox + edge + 1, oy + pos, EARTH_DARK)
            rect(s, ox, oy, edge - 3, pos, edge - 1, pos, WATER_DEEP)
            if pos % 4 in (0, 1):
                px(s, ox + edge - 1, oy + pos, WATER_CREST)
    for _ in range(8):
        x = rng.randrange(2, TILE - 2)
        y = rng.randrange(2, TILE - 2)
        px(s, ox + x, oy + y, WATER_CREST)


def shore_corner(s: Sprite, index: int, corner: str) -> None:
    ox, oy = fill(s, index, WATER)

    def inside(x: int, y: int) -> bool:
        margin = (x // 4 + y // 4 + index) % 3
        return (
            (corner == "nw" and x < 16 + margin and y < 16 + margin)
            or (corner == "ne" and x > 15 - margin and y < 16 + margin)
            or (corner == "sw" and x < 16 + margin and y > 15 - margin)
            or (corner == "se" and x > 15 - margin and y > 15 - margin)
        )

    for y in range(TILE):
        for x in range(TILE):
            if inside(x, y):
                px(s, ox + x, oy + y, EARTH)
    for y in range(TILE):
        for x in range(TILE):
            neighbours = (
                inside(x + 1, y), inside(x - 1, y),
                inside(x, y + 1), inside(x, y - 1),
            )
            if inside(x, y) and not all(neighbours):
                px(s, ox + x, oy + y, SAND)
            elif not inside(x, y) and any(neighbours) and (x * 7 + y * 3) % 11 == 0:
                px(s, ox + x, oy + y, WATER_CREST)
    for _ in range(7):
        rng = random.Random(9200 + index * 11 + _)
        x = rng.randrange(1, TILE - 1)
        y = rng.randrange(1, TILE - 1)
        if not inside(x, y):
            px(s, ox + x, oy + y, WATER_CREST)


def puddle_tile(s: Sprite, index: int, salty: bool = False) -> None:
    mud_tile(s, index, variant=4, base=SAND if salty else EARTH)
    ox, oy = origin(index)
    s.ellipse(ox + 5, oy + 7, ox + 26, oy + 25, WATER, fill=True)
    s.ellipse(ox + 6, oy + 8, ox + 24, oy + 22, WATER_LIGHT, fill=True)
    s.ellipse(ox + 8, oy + 10, ox + 21, oy + 19, WATER, fill=True)
    rect(s, ox, oy, 8, 11, 12, 11, WATER_CREST)
    rect(s, ox, oy, 17, 17, 21, 17, WATER_CREST)
    if salty:
        rect(s, ox, oy, 3, 22, 7, 23, PLASTER)
        rect(s, ox, oy, 25, 6, 28, 7, PLASTER)


def gravel_tile(s: Sprite, index: int) -> None:
    mud_tile(s, index, variant=5, base=EARTH_DARK)
    ox, oy = origin(index)
    rng = random.Random(10100)
    for _ in range(28):
        x = rng.randrange(2, TILE - 4)
        y = rng.randrange(2, TILE - 3)
        w = rng.randrange(1, 4)
        h = rng.randrange(1, 3)
        rect(s, ox, oy, x, y, x + w, y + h, STONE_SHADOW)
        rect(s, ox, oy, x, y, x + w - 1, y, STONE)
        if rng.random() < 0.4:
            px(s, ox + x, oy + y, STONE_LIGHT)


def driftwood_tile(s: Sprite, index: int) -> None:
    mud_tile(s, index, variant=6)
    ox, oy = origin(index)
    s.polygon(
        [
            (ox + 3, oy + 22), (ox + 8, oy + 18), (ox + 14, oy + 19),
            (ox + 25, oy + 15), (ox + 29, oy + 17), (ox + 21, oy + 22),
            (ox + 12, oy + 24),
        ],
        WOOD_DARK,
    )
    s.polygon(
        [
            (ox + 5, oy + 21), (ox + 10, oy + 19), (ox + 16, oy + 20),
            (ox + 25, oy + 17), (ox + 23, oy + 20), (ox + 13, oy + 23),
        ],
        WOOD,
    )
    line(s, ox, oy, 7, 21, 22, 18, WOOD_LIGHT)
    line(s, ox, oy, 15, 20, 19, 17, WOOD_LIGHT)
    line(s, ox, oy, 18, 21, 19, 18, WOOD_DARK)


def cracked_mud_tile(s: Sprite, index: int) -> None:
    sand_tile(s, index, variant=3)
    ox, oy = origin(index)
    cracks = [
        [(4, 8), (9, 11), (14, 10), (19, 14)],
        [(19, 14), (24, 12), (29, 15)],
        [(14, 10), (12, 16), (15, 21), (13, 27)],
        [(19, 14), (22, 20), (28, 23)],
        [(6, 21), (10, 19), (15, 21)],
    ]
    for crack in cracks:
        for (x0, y0), (x1, y1) in zip(crack, crack[1:]):
            line(s, ox, oy, x0, y0, x1, y1, EARTH_DARK)
    for pts in ((7, 12), (20, 18), (26, 25)):
        px(s, ox + pts[0], oy + pts[1], PLASTER)


def wet_stone_tile(s: Sprite, index: int) -> None:
    stone_road(s, index, variant=2)
    ox, oy = origin(index)
    rect(s, ox, oy, 2, 4, 12, 4, WATER_LIGHT)
    rect(s, ox, oy, 18, 20, 29, 20, WATER)
    for x in (5, 23):
        px(s, ox + x, oy + 9, WATER_CREST)
    for x, y in ((7, 7), (26, 26)):
        px(s, ox + x, oy + y, WATER_CREST)


def mud_grass_tile(s: Sprite, index: int) -> None:
    mud_tile(s, index, variant=7)
    ox, oy = origin(index)
    for y in range(14, TILE):
        for x in range(TILE):
            if (x * 3 + y * 5) % 9 < 4:
                px(s, ox + x, oy + y, REED_DARK)
    for _ in range(18):
        x = (7 * _ + 3) % TILE
        y = 16 + (_ * 5) % 14
        px(s, ox + x, oy + y, REED)
        if _ % 3 == 0:
            px(s, ox + x, oy + y - 1, REED_LIGHT)


def mountain_tile(s: Sprite, index: int, variant: int = 0) -> None:
    """Opaque fractured rock: reads as a solid blocker, never as shallow water."""
    ox, oy = fill(s, index, STONE_DARK)
    shift = (variant % 4) * 2
    peak = 5 if variant < 4 else 2
    s.polygon(
        [
            (ox + 0, oy + 12), (ox + 5 + shift, oy + peak + 3),
            (ox + 13, oy + 9), (ox + 21 - shift, oy + peak),
            (ox + 27, oy + 8), (ox + 32, oy + 14),
            (ox + 32, oy + 32), (ox + 0, oy + 32),
        ],
        STONE,
    )
    s.polygon(
        [
            (ox + 5 + shift, oy + peak + 3), (ox + 13, oy + 9),
            (ox + 12, oy + 20), (ox + 4, oy + 29), (ox + 0, oy + 32),
            (ox + 0, oy + 12),
        ],
        STONE_LIGHT,
    )
    s.polygon(
        [
            (ox + 13, oy + 9), (ox + 21 - shift, oy + peak),
            (ox + 25, oy + 18), (ox + 19, oy + 28), (ox + 12, oy + 20),
        ],
        STONE_SHADOW,
    )
    s.polygon(
        [
            (ox + 25, oy + 18), (ox + 27, oy + 8), (ox + 32, oy + 14),
            (ox + 32, oy + 32), (ox + 22, oy + 32), (ox + 19, oy + 28),
        ],
        STONE_DARK,
    )
    line(s, ox, oy, 13, 9, 12, 20, STONE_HIGHLIGHT)
    line(s, ox, oy, 12, 20, 16, 24, STONE_SHADOW)
    line(s, ox, oy, 16, 24, 14, 31, INK)
    line(s, ox, oy, 25, 18, 28, 23, STONE_HIGHLIGHT)
    line(s, ox, oy, 28, 23, 26, 30, INK)
    rng = random.Random(15000 + variant)
    for _ in range(12):
        x = rng.randrange(3, TILE - 3)
        y = rng.randrange(14, TILE - 2)
        px(s, ox + x, oy + y, STONE_HIGHLIGHT if rng.random() < 0.45 else STONE_SHADOW)


def build_terrain() -> Sprite:
    s = atlas(rows=5)
    mud_tile(s, 0, 0)
    mud_tile(s, 1, 1, base=EARTH_DARK)
    sand_tile(s, 2, 0)
    sand_tile(s, 3, 1)
    water_tile(s, 4, deep=False, variant=0)
    water_tile(s, 5, deep=False, variant=1)
    water_tile(s, 6, deep=True, variant=0)
    water_tile(s, 7, deep=True, variant=1)
    mud_grass_tile(s, 8)
    reed_bed(s, 9)
    stone_road(s, 10, 0)
    stone_road(s, 11, 1)
    earth_road(s, 12, 0)
    earth_road(s, 13, 1)
    dock_planks(s, 14, vertical=True)
    dock_planks(s, 15, vertical=False)
    shore_side(s, 16, "n")
    shore_side(s, 17, "s")
    shore_side(s, 18, "e")
    shore_side(s, 19, "w")
    shore_corner(s, 20, "nw")
    shore_corner(s, 21, "ne")
    shore_corner(s, 22, "sw")
    shore_corner(s, 23, "se")
    puddle_tile(s, 24)
    puddle_tile(s, 25, salty=True)
    gravel_tile(s, 26)
    driftwood_tile(s, 27)
    cracked_mud_tile(s, 28)
    sand_tile(s, 29, 2)
    wet_stone_tile(s, 30)
    mud_grass_tile(s, 31)
    for variant in range(8):
        mountain_tile(s, 32 + variant, variant)
    return s


def stone_wall(s: Sprite, index: int, variant: int = 0) -> None:
    ox, oy = fill(s, index, STONE)
    courses = (
        (0, 10, (0, 13, 25)),
        (11, 10, (6, 19)),
        (22, 9, (0, 16)),
    )
    for y0, height, joints in courses:
        y1 = y0 + height - 1
        rect(s, ox, oy, 0, y0, TILE - 1, y0, STONE_DARK)
        for x in joints:
            rect(s, ox, oy, x, y0, x, y1, STONE_DARK)
        spans = list(zip(joints, joints[1:] + (TILE,)))
        for x0, x1 in spans:
            left = x0 + 1
            right = x1 - 1
            if right <= left:
                continue
            rect(s, ox, oy, left, y0 + 1, left + (right - left) // 2, y0 + 1, STONE_LIGHT)
            rect(s, ox, oy, left, y0 + 2, left, y0 + 4, STONE_LIGHT)
            rect(s, ox, oy, left + 2, y1, right, y1, STONE_DARK)
            if right - left > 5:
                rect(s, ox, oy, left + 3, y0 + height - 3, right - 2, y0 + height - 2,
                     STONE_DARK)
    rng = random.Random(11000 + variant)
    for _ in range(10 + variant * 3):
        x = rng.randrange(2, TILE - 2)
        y = rng.randrange(2, TILE - 2)
        px(s, ox + x, oy + y, STONE_HIGHLIGHT if rng.random() < 0.28 else STONE_SHADOW)
    if variant == 1:
        line(s, ox, oy, 7, 0, 7, 15, STONE_SHADOW)
        px(s, ox + 10, oy + 8, STONE_HIGHLIGHT)
        px(s, ox + 24, oy + 25, STONE_HIGHLIGHT)
    if variant == 2:
        for x, y in ((3, 4), (4, 5), (5, 5), (24, 12), (23, 13), (7, 27), (8, 27)):
            px(s, ox + x, oy + y, REED_DARK)
        rect(s, ox, oy, 18, 18, 21, 19, STONE_SHADOW)



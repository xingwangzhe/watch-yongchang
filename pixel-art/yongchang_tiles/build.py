def compose_preview(terrain: Sprite, architecture: Sprite, props: Sprite) -> Image.Image:
    scene = Image.new("RGBA", (640, 352), PAL[INK])
    terrain_img = terrain.composite()
    architecture_img = architecture.composite()
    props_img = props.composite()

    def cell(source: Image.Image, index: int) -> Image.Image:
        x, y = origin(index)
        return source.crop((x, y, x + TILE, y + TILE))

    def paste(source: Image.Image, index: int, tx: int, ty: int) -> None:
        scene.alpha_composite(cell(source, index), (tx * TILE, ty * TILE))

    for ty in range(11):
        for tx in range(20):
            if ty < 5:
                if ty == 4:
                    index = 17
                elif ty <= 1:
                    index = (16 if (tx * 3 + ty) % 7 == 0 else 0)
                    if (tx * 5 + ty) % 11 == 0:
                        index = 1
                else:
                    index = 24 if (tx + ty) % 9 == 0 else 8 if (tx * 2 + ty) % 7 == 0 else 0
            else:
                index = 2 if ty == 5 or (ty == 9 and tx < 12) else 6
                if ty >= 8 and (tx + ty) % 8 == 0:
                    index = 7
            paste(terrain_img, index, tx, ty)

    for tx in range(1, 8):
        for ty in range(6, 9):
            paste(terrain_img, 15, tx, ty)
        paste(architecture_img, 24, tx, 6)
        paste(architecture_img, 24, tx, 8)
    for ty in range(6, 9):
        for tx in range(8, 11):
            paste(terrain_img, 14, tx, ty)
        paste(architecture_img, 31, 8, ty)
        paste(architecture_img, 31, 10, ty)
    for ty in range(8, 11):
        for tx in range(13, 19):
            paste(terrain_img, 32 + ((tx * 3 + ty * 5) % 8), tx, ty)
    paste(props_img, 9, 4, 10)

    for tx in range(1, 6):
        paste(terrain_img, 9, tx, 2)
        paste(props_img, 0, tx, 1)
    paste(terrain_img, 26, 0, 7)

    for tx in range(8, 20):
        paste(architecture_img, 5, tx, 4)
        paste(architecture_img, 3 if tx % 6 == 3 else 0, tx, 5)
        paste(architecture_img, 4, tx, 6)

    for x0, x1 in ((8, 12), (16, 19)):
        for tx in range(x0, x1 + 1):
            paste(architecture_img, 12, tx, 0)
            paste(architecture_img, 13, tx, 1)
            paste(architecture_img, 14, tx, 2)
            paste(architecture_img, 8 if tx % 2 else 9, tx, 3)
    for tx in range(13, 16):
        paste(architecture_img, 12, tx, 2)
        paste(architecture_img, 13, tx, 3)
        paste(architecture_img, 14, tx, 4)

    paste(architecture_img, 16, 13, 5)
    paste(architecture_img, 17, 14, 5)
    paste(architecture_img, 18, 15, 5)
    paste(architecture_img, 19, 13, 6)
    paste(architecture_img, 20, 14, 6)
    paste(architecture_img, 21, 15, 6)

    for tx, ty, idx in (
        (9, 5, 27), (11, 5, 27), (17, 5, 27),
        (9, 2, 8), (18, 2, 8),
    ):
        paste(architecture_img, idx, tx, ty)
    for tx, ty, idx in (
        (5, 6, 5), (6, 6, 6),
        (7, 8, 7), (6, 7, 11),
        (0, 3, 2),
        (18, 3, 4), (19, 3, 0),
    ):
        if idx == 4:
            paste(architecture_img, 24, tx, ty)
        else:
            paste(props_img, idx, tx, ty)

    paste(architecture_img, 25, 12, 6)
    paste(architecture_img, 24, 16, 4)
    return scene


def compose_seam_check(terrain: Sprite) -> Image.Image:
    source = terrain.composite()
    checks = (0, 2, 3, 4, 10, 14, 15, 32)
    cell_w = TILE * 3
    gap = 8
    sheet = Image.new("RGBA", (len(checks) * (cell_w + gap) + gap, cell_w + gap * 2),
                      PAL[INK])
    for column, index in enumerate(checks):
        x, y = origin(index)
        stamp = source.crop((x, y, x + TILE, y + TILE))
        for ty in range(3):
            for tx in range(3):
                sheet.alpha_composite(stamp, (gap + column * (cell_w + gap) + tx * TILE,
                                              gap + ty * TILE))
    return sheet


